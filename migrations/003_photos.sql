-- Несколько фотографий на карточку.
--
-- Поле photo остаётся обложкой: по нему строится плитка в выдаче и сортировка
-- «сначала с фото». photos — весь набор, JSON-массив путей, обложка первая.
--
-- Главное тут не про красоту. Одно объявление приходит из нескольких каналов,
-- и у каждого перепоста своё фото. Раньше при склейке всё, кроме первого,
-- терялось; теперь карточка собирает их вместе — и оказывается полнее, чем
-- любой исходный пост.

ALTER TABLE listing ADD COLUMN photos TEXT;

-- У всего, что уже есть, набор состоит из одной обложки.
UPDATE listing
   SET photos = '["' || photo || '"]'
 WHERE photo IS NOT NULL AND photos IS NULL;
