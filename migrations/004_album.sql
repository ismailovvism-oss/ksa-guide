-- Все снимки поста, а не первый попавшийся.
--
-- В Telegram альбом — это несколько сообщений с общим grouped_id, и подпись
-- есть только у одного из них. Раньше каждое такое сообщение стало бы
-- отдельной записью: одна с текстом, остальные — безтекстовым мусором,
-- а снимки разъехались бы по разным карточкам.
--
-- Теперь альбом собирается в одну запись: media_path — обложка (по ней
-- считается перцептивный хеш для дедупа), media_paths — весь набор.
--
-- Это же чинит давнюю потерю: первая выгрузка канала брала из поста один
-- снимок и копировала его всем описанным в посте местам — 201 запись,
-- но всего 120 разных изображений.

ALTER TABLE raw_message ADD COLUMN media_paths TEXT;

UPDATE raw_message
   SET media_paths = '["' || media_path || '"]'
 WHERE media_path IS NOT NULL AND media_paths IS NULL;
